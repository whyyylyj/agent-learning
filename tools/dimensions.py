def dim_card(d, case_prefix):
    steps_data = [
        ("Struggle", d["struggle"]), ("问题拆解", d["decompose"]), ("调研与测试", d["research"]),
        ("解决步骤", "<ul class='pts'>" + "".join(f"<li>{x}</li>" for x in d["solve"]) + "</ul>"),
        ("验证思路", d["validate"]), ("达成效果", d["effect"]),
        ("迭代新问题", d["new_problem"]), ("业界对比", d["industry"]), ("设计巧思", d["insight"]),
    ]
    steps = "".join(f'<div class="sstep"><span class="stag">{lab}</span><div>{txt}</div></div>' for lab, txt in steps_data)
    return f"""<div class="tot">
<div class="tot-head"><h3>维度 {d["no"]} · {d["title"]}</h3><span class="sub">{case_prefix}</span></div>
<div class="box ideab" style="margin:8px 0"><b>价值点：</b>{d["value"]}</div>
<div class="strug">{steps}</div>
</div>"""
